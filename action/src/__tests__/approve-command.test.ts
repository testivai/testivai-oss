/**
 * The `/testivai approve` command in a pull request comment
 * (parseApproveCommand, used by approve/action.yml's auth step).
 *
 * Only the comment's first line is read. A note, a signature or a footer
 * below it (Claude Code ends every comment it posts with one) is ignored, so
 * it neither stops the command nor becomes a snapshot name. A first line that
 * is a bare `/testivai approve` means `--all` only when it is the whole
 * comment: with more lines below it, the target is asked for, never assumed,
 * because names written on the next line used to be read as the target.
 */

import { buildNeedsTargetReply, parseApproveCommand } from '../approve';

/** The parser the auth step used before: the whole trimmed body, one regex. */
function legacyParse(body: string): { cmd: string; target: string } | null {
  const match = body.trim().match(/^\/testivai\s+(approve)\s*(.+)?$/i);
  return match ? { cmd: match[1].toLowerCase(), target: (match[2] ?? '--all').trim() } : null;
}

const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

describe('parseApproveCommand: a single-line comment', () => {
  it.each([
    ['/testivai approve', '--all'],
    ['/testivai approve --all', '--all'],
    ['/testivai approve home', 'home'],
    ['/testivai approve home about', 'home about'],
    ['/TestivAI APPROVE Home', 'Home'],
    ['   /testivai   approve   home   ', 'home'],
    ['\n\n/testivai approve home\n\n', 'home'],
  ])('%j → target %j', (body, target) => {
    expect(parseApproveCommand(body)).toEqual({ cmd: 'approve', target });
  });

  it('gives what the previous parser gave, for every single-line comment', () => {
    const bodies = [
      '/testivai approve',
      '/testivai approve ',
      '/testivai approve --all',
      '/testivai approve home',
      '/testivai approve home about',
      '/testivai approve\thome',
      '/TESTIVAI Approve home',
      '/testivai  approve  --all  ',
      '/testivai approvehome',
      "/testivai approve x'+(globalThis.__pwned=1)+'",
      '/testivai approve --all --- _Generated by [Claude Code](https://claude.ai/code)_',
      '/testivai',
      '/testivai reject home',
      '/testivaiapprove',
      'testivai approve',
      'Looks good',
      '',
      '   ',
    ];
    for (const body of bodies) expect([body, parseApproveCommand(body)]).toEqual([body, legacyParse(body)]);
  });
});

describe('parseApproveCommand: a command with more lines below it', () => {
  it('a note on later lines is ignored', () => {
    expect(parseApproveCommand('/testivai approve --all\n\nLooks good, thanks')).toEqual({ cmd: 'approve', target: '--all' });
  });

  it('a footer is ignored', () => {
    expect(parseApproveCommand(`/testivai approve --all${FOOTER}`)).toEqual({ cmd: 'approve', target: '--all' });
    expect(parseApproveCommand(`/testivai approve home${FOOTER}`)).toEqual({ cmd: 'approve', target: 'home' });
  });

  it('a named snapshot is the target, and the note under it is not', () => {
    expect(parseApproveCommand('/testivai approve home\nLooks good')).toEqual({ cmd: 'approve', target: 'home' });
    expect(parseApproveCommand('/testivai approve home about\n\nthe new header is intended')).toEqual({ cmd: 'approve', target: 'home about' });
  });

  it('CRLF line endings: the first line ends at \\r\\n, and no \\r reaches the target', () => {
    expect(parseApproveCommand('/testivai approve home\r\n\r\nLooks good\r\n')).toEqual({ cmd: 'approve', target: 'home' });
    expect(parseApproveCommand('/testivai approve --all\r\nthanks')).toEqual({ cmd: 'approve', target: '--all' });
    expect(parseApproveCommand('/testivai approve home\r\n')).toEqual({ cmd: 'approve', target: 'home' });
  });

  it.each([
    ['a lone \\r', '\r'],
    ['U+2028 line separator', '\u2028'],
    ['U+2029 paragraph separator', '\u2029'],
  ])('%s also ends the first line', (_label, eol) => {
    expect(parseApproveCommand(`/testivai approve home${eol}Looks good`)).toEqual({ cmd: 'approve', target: 'home' });
  });

  it.each([
    ['names on the next line', '/testivai approve\nhome'],
    ['names after a blank line', '/testivai approve\n\nhome about'],
    ['a note', '/testivai approve\n\nLooks good, thanks'],
    ['a footer', `/testivai approve${FOOTER}`],
    ['CRLF', '/testivai approve\r\nhome'],
    ['spaces after the command', '/testivai approve   \nhome'],
  ])('a bare /testivai approve with %s below it has no target (asked for, never --all)', (_label, body) => {
    expect(parseApproveCommand(body)).toEqual({ cmd: 'approve', target: null });
  });

  it('a bare /testivai approve followed only by blank lines is the whole comment: --all', () => {
    expect(parseApproveCommand('/testivai approve\n\n  \r\n')).toEqual({ cmd: 'approve', target: '--all' });
  });

  it('no target ever holds a line break', () => {
    const eols = ['\n', '\r\n', '\r', '\u2028', '\u2029'];
    for (const eol of eols) {
      for (const body of [`/testivai approve a${eol}b`, `/testivai approve a b${eol}${eol}c d${eol}`, `/testivai approve --all${eol}x`]) {
        const target = parseApproveCommand(body)?.target ?? '';
        expect([body, /[\n\r\u2028\u2029]/.test(target)]).toEqual([body, false]);
      }
    }
  });
});

describe('parseApproveCommand: not a command', () => {
  it.each([
    ['plain text', 'Looks good'],
    ['the command on a later line', 'Thanks!\n/testivai approve --all'],
    ['a quoted command', '> /testivai approve --all\n\nShould I run this?'],
    ['the command in a code block', '```\n/testivai approve --all\n```'],
    ['/testivai alone', '/testivai'],
    ['another /testivai word', '/testivai reject home'],
    ['the verb on the next line', '/testivai\napprove home'],
    ['an empty comment', ''],
    ['whitespace', ' \n\t '],
  ])('%s', (_label, body) => {
    expect(parseApproveCommand(body)).toBeNull();
  });

  it('a missing body', () => {
    expect(parseApproveCommand(undefined)).toBeNull();
    expect(parseApproveCommand(null)).toBeNull();
  });
});

describe('buildNeedsTargetReply', () => {
  const reply = buildNeedsTargetReply('octocat');

  it('says nothing was approved, and how to name the target on the first line', () => {
    expect(reply).toMatch(/^@octocat — /);
    expect(reply).toContain('nothing was approved');
    expect(reply).toContain('first line');
    expect(reply).toContain('/testivai approve <name>');
    expect(reply).toContain('/testivai approve --all');
  });

  it('is not itself a command, so a reply posted with a token that starts workflows cannot approve', () => {
    expect(parseApproveCommand(reply)).toBeNull();
  });
});
